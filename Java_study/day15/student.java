package day15;
// source 제너레이트 게터엔 세터 눌러서 걍 바로가능
public class student {

	private String name;
	private int age;
	private String apt;
	private String number;
	private int kor;
	private int erg;
	private int math;
	private int sum;
	private int avg;
	
	public String getName() {
		return this.name;
	}
	
	public void setName(String name) {
		this.name = name;
	}
	
	public String getApt() {
		return this.apt;
	}
	
	public void setApt(String apt) {
		this.apt = apt;
	}
	
	public int getAge() {
		return this.age;
	}
	
	public void setAge(int age) {
		this.age = age;
	}
	
	public String getNumber() {
		return this.number;
	}
	
	public void setNumber(String number) {
		this.number = number;
	}
	
	public int getKor() {
		return this.kor;
	}
	
	public void setKor(int kor) {
		this.kor = kor;
	}
	
	public int getErg() {
		return this.erg;
	}
	
	public void setErg(int erg) {
		this.erg = erg;
	}
	
	public int getMath() {
		return this.math;
	}
	
	public void setMath(int math) {
		this.math = math;
	}
	
	public int getSum() {
		return this.sum;
	}
	
	public void setSum(int sum) {
		this.sum = sum;
	}
	
	public int getAvg() {
		return this.avg;
	}
	
	public void setAvg(int avg) {
		this.avg = avg;
	}
	
	
}
